<?php

/**
 * Copies the Markdown parser into the hosted web backend (the multi-user `php_backend`), so the web
 * version and the package always parse a document exactly the same way.
 *
 *   php scripts/sync-hosted.php --backend=/path/to/php_backend
 *
 * The parser runs on PHP 7.4 (the hosted server's version): scripts/hosted/polyfills.php supplies str_contains() and friends
 * there. It is copied only to the hosted backend; the Composer package needs PHP 8.1 and does not ship it.
 * Writes <backend>/includes/parser/ (the namespaced classes) and <backend>/includes/markdownOpenApiParser.php,
 * which loads them and keeps the global `MarkdownOpenApiParser` class the hosted endpoints already call.
 * Run it again after changing anything in src/Parser/ or src/MarkdownOpenApiParser.php.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$backend = null;
foreach (array_slice($argv, 1) as $arg) {
    if (str_starts_with($arg, '--backend=')) $backend = substr($arg, strlen('--backend='));
}
if ($backend === null || !is_dir($backend . '/includes')) {
    fwrite(STDERR, "Usage: php scripts/sync-hosted.php --backend=PATH_TO_php_backend (the folder that contains includes/)\n");
    exit(1);
}
$backend = rtrim(str_replace('\\', '/', realpath($backend) ?: $backend), '/');
$target = $backend . '/includes/parser';

function copyTree(string $from, string $to): void
{
    if (!is_dir($to) && !mkdir($to, 0775, true) && !is_dir($to)) {
        fwrite(STDERR, "Could not create {$to}\n");
        exit(1);
    }
    foreach (scandir($from) ?: [] as $item) {
        if ($item === '.' || $item === '..') continue;
        $source = "{$from}/{$item}";
        if (is_dir($source)) copyTree($source, "{$to}/{$item}");
        elseif (str_ends_with($item, '.php') && !copy($source, "{$to}/{$item}")) {
            fwrite(STDERR, "Could not write {$to}/{$item}\n");
            exit(1);
        }
    }
}

// Drop files of classes that no longer exist, then copy the current ones.
foreach (glob($target . '/Parser/*.php') ?: [] as $old) unlink($old);
copyTree($root . '/src/Parser', $target . '/Parser');
copy($root . '/src/MarkdownOpenApiParser.php', $target . '/MarkdownOpenApiParser.php');
// The hosted autoloader is the package's, with the polyfills loaded first (the loader below calls str_starts_with()).
$autoload = str_replace("\r\n", "\n", (string) file_get_contents($root . '/src/autoload.php'));
$marker = "declare(strict_types=1);\n\n";
if (!str_contains($autoload, $marker)) {
    fwrite(STDERR, "src/autoload.php no longer matches what this script expects; update scripts/sync-hosted.php\n");
    exit(1);
}
file_put_contents($target . '/autoload.php', str_replace($marker, $marker . "require_once __DIR__ . '/polyfills.php';\n\n", $autoload));
copy($root . '/scripts/hosted/polyfills.php', $target . '/polyfills.php');

$loader = <<<'PHP'
<?php

/**
 * Loads the Markdown -> OpenAPI parser and exposes it as the global `MarkdownOpenApiParser` class.
 *
 * GENERATED by scripts/sync-hosted.php in the api-version-platform package (src/Parser/ and
 * src/MarkdownOpenApiParser.php). Do not edit includes/parser/ by hand: change the package and re-run the script.
 *
 * MarkdownOpenApiParser::parse($markdown) returns { openapi, warnings, statistics, errors }. Problems in a strict
 * document (front-matter header with `avp: 1`) are reported as warnings; nothing here ever blocks saving a version.
 */

require_once __DIR__ . '/parser/autoload.php';

if (!class_exists('MarkdownOpenApiParser', false)) {
    class_alias(\Mohammad\ApiVersionPlatform\MarkdownOpenApiParser::class, 'MarkdownOpenApiParser');
}

PHP;
file_put_contents($backend . '/includes/markdownOpenApiParser.php', $loader);
fwrite(STDOUT, "Synced the parser into {$backend}/includes (parser/ + markdownOpenApiParser.php)\n");
